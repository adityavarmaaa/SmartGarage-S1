CREATE TABLE parking_areas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_code text NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'active'
);
CREATE TABLE event_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);
CREATE TABLE vehicle_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);
CREATE TABLE vehicle_colors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);
CREATE TABLE cameras (
    camera_id text PRIMARY KEY,
    parking_area_id text NOT NULL REFERENCES parking_areas(area_code),
    parking_area_fk bigint NOT NULL REFERENCES parking_areas(id),
    name text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE parking_slots (
    camera_id text REFERENCES cameras(camera_id),
    slot_id text,
    polygon jsonb,
    polygon_hmac text,
    status text NOT NULL DEFAULT 'available',
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (camera_id, slot_id)
);
CREATE TABLE vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number text,
    plate_number_ciphertext text,
    plate_number_hmac text UNIQUE,
    vehicle_type_fk bigint REFERENCES vehicle_types(id),
    color_fk bigint REFERENCES vehicle_colors(id),
    vehicle_type text,
    color text,
    first_seen_at timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE parking_slot_state (
    camera_id text,
    slot_id text,
    parking_area_id text NOT NULL REFERENCES parking_areas(area_code),
    status text NOT NULL CHECK (status IN ('available', 'occupied')),
    vehicle_fk bigint REFERENCES vehicles(id),
    vehicle_uid text,
    track_id bigint,
    occupied_since timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    plate_number text,
    plate_number_ciphertext text,
    plate_number_hmac text,
    PRIMARY KEY (camera_id, slot_id),
    FOREIGN KEY (camera_id, slot_id) REFERENCES parking_slots(camera_id, slot_id)
);
CREATE TABLE parking_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type text NOT NULL REFERENCES event_types(code),
    event_type_fk bigint NOT NULL REFERENCES event_types(id),
    camera_id text NOT NULL REFERENCES cameras(camera_id),
    parking_area_id text NOT NULL REFERENCES parking_areas(area_code),
    vehicle_uid text,
    track_id bigint,
    timestamp timestamptz NOT NULL,
    captured_at timestamptz,
    vehicle_type text,
    vehicle_type_confidence double precision,
    color text,
    color_confidence double precision,
    plate_number text,
    plate_number_ciphertext text,
    plate_number_hmac text,
    plate_confidence double precision,
    slot_id text,
    slot_confidence double precision,
    vehicle_snapshot text,
    plate_snapshot text,
    vehicle_fk bigint REFERENCES vehicles(id),
    observed_vehicle_type text,
    observed_color text,
    observed_plate_number text,
    observed_plate_number_ciphertext text,
    observed_plate_number_hmac text,
    FOREIGN KEY (camera_id, slot_id) REFERENCES parking_slots(camera_id, slot_id)
);
CREATE TABLE parking_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number text,
    plate_number_ciphertext text,
    plate_number_hmac text,
    vehicle_type text,
    color text,
    vehicle_fk bigint REFERENCES vehicles(id),
    vehicle_uid text,
    parking_area_id text NOT NULL REFERENCES parking_areas(area_code),
    camera_id text NOT NULL REFERENCES cameras(camera_id),
    slot_id text,
    entry_time timestamptz NOT NULL,
    exit_time timestamptz,
    duration_seconds bigint,
    status text NOT NULL CHECK (status IN ('parked', 'exited')),
    entry_screenshot_url text,
    exit_screenshot_url text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (camera_id, slot_id) REFERENCES parking_slots(camera_id, slot_id)
);
CREATE UNIQUE INDEX parking_sessions_active_uid
    ON parking_sessions (parking_area_id, camera_id, vehicle_uid)
    WHERE vehicle_uid IS NOT NULL AND status = 'parked';
CREATE INDEX parking_sessions_vehicle_history ON parking_sessions (vehicle_fk, entry_time DESC);
CREATE INDEX parking_events_vehicle_history ON parking_events (vehicle_fk, timestamp DESC);
CREATE INDEX parking_events_type_time ON parking_events (event_type_fk, timestamp);
CREATE INDEX parking_events_retry_lookup ON parking_events (parking_area_id, camera_id, event_type, timestamp);
CREATE INDEX parking_slot_state_vehicle ON parking_slot_state (vehicle_fk) WHERE status = 'occupied';

